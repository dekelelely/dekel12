// Turns moves.json (exported from clawd-engine.js) into static Rust data: src/moves.rs includes the result.
use serde_json::Value;
use std::fmt::Write;

fn num(f: &Value, key: &str) -> f64 {
    f.get(key).and_then(Value::as_f64).unwrap_or(0.0)
}

fn flag(f: &Value, key: &str) -> bool {
    f.get(key).and_then(Value::as_bool).unwrap_or(false)
}

fn word<'a>(f: &'a Value, key: &str) -> Option<&'a str> {
    f.get(key).and_then(Value::as_str)
}

fn variant(name: Option<&str>, options: &[(&str, &str)], default: &str) -> String {
    match name {
        None => default.to_string(),
        Some(n) => options.iter().find(|(k, _)| *k == n).unwrap_or_else(|| panic!("unknown value {n:?}")).1.to_string(),
    }
}

fn frame(f: &Value) -> String {
    let mut s = String::from("Frame {");
    let eyes = variant(
        word(f, "eyes"),
        &[("left", "Eyes::Left"), ("right", "Eyes::Right"), ("closed", "Eyes::Closed"), ("wink", "Eyes::Wink")],
        "",
    );
    let arms = variant(word(f, "arms"), &[("up", "Arms::Up"), ("one-up", "Arms::OneUp")], "");
    let feet = variant(word(f, "feet"), &[("left", "Feet::Left"), ("right", "Feet::Right")], "");
    for (key, v) in [("eyes", eyes), ("arms", arms), ("feet", feet)] {
        if !v.is_empty() {
            write!(s, " {key}: {v},").unwrap();
        }
    }
    if num(f, "offset") != 0.0 {
        write!(s, " offset: {},", num(f, "offset") as i8).unwrap();
    }
    for (json, rust) in [
        ("x", "x"),
        ("angle", "angle"),
        ("lift", "lift"),
        ("flip", "flip"),
        ("roll", "roll"),
        ("squat", "squat"),
        ("lean", "lean"),
        ("kick", "kick"),
        ("strum", "strum"),
        ("bang", "bang"),
        ("guitar", "guitar"),
        ("laptop", "laptop"),
        ("dumbbell", "dumbbell"),
        ("curlL", "curl_l"),
        ("curlR", "curl_r"),
    ] {
        let v = num(f, json);
        if v != 0.0 {
            write!(s, " {rust}: {v:?},").unwrap();
        }
    }
    if let Some(fret) = f.get("fret").and_then(Value::as_f64) {
        write!(s, " fret: {fret:?},").unwrap();
    }
    for (json, rust) in
        [("windmill", "windmill"), ("zap", "zap"), ("flash", "flash"), ("typing", "typing"), ("ripple", "ripple")]
    {
        if flag(f, json) {
            write!(s, " {rust}: true,").unwrap();
        }
    }
    if num(f, "confetti") != 0.0 {
        write!(s, " confetti: {},", num(f, "confetti") as u8).unwrap();
    }
    let notes = variant(word(f, "notes"), &[("above", "Notes::Above"), ("side", "Notes::Side")], "");
    let poof = variant(word(f, "poof"), &[("dot", "Poof::Dot"), ("wave", "Poof::Wave")], "");
    let shadow = variant(word(f, "shadow"), &[("wide", "Shadow::Wide"), ("narrow", "Shadow::Narrow")], "");
    for (key, v) in [("notes", notes), ("poof", poof), ("shadow", shadow)] {
        if !v.is_empty() {
            write!(s, " {key}: {v},").unwrap();
        }
    }
    s.push_str(" ..D }");
    s
}

fn frames(list: &Value) -> String {
    let items: Vec<String> = list.as_array().unwrap().iter().map(frame).collect();
    format!("&[\n        {},\n    ]", items.join(",\n        "))
}

fn main() {
    println!("cargo:rerun-if-changed=moves.json");
    let text = std::fs::read_to_string("moves.json").expect("moves.json");
    let data: Value = serde_json::from_str(&text).expect("moves.json is JSON");
    let mut out = String::new();
    writeln!(out, "// Generated by build.rs from moves.json.").unwrap();
    writeln!(out, "pub const FRAME_MS: f64 = {:?};", data["frameMs"].as_f64().unwrap()).unwrap();
    let moves = data["moves"].as_array().unwrap();
    writeln!(out, "pub static MOVES: [Move; {}] = [", moves.len()).unwrap();
    for m in moves {
        writeln!(out, "    Move {{ name: {:?}, frames: {} }},", m["name"].as_str().unwrap(), frames(&m["frames"]))
            .unwrap();
    }
    writeln!(out, "];").unwrap();
    writeln!(out, "pub static IDLE: &[Frame] = {};", frames(&data["idle"])).unwrap();
    for (key, name) in [("entrances", "ENTRANCES"), ("onClick", "ON_CLICK")] {
        let list = data[key].as_array().unwrap();
        let names: Vec<String> = list.iter().map(|n| format!("{:?}", n.as_str().unwrap())).collect();
        writeln!(out, "pub static {name}: [&str; {}] = [{}];", list.len(), names.join(", ")).unwrap();
    }
    for (key, name) in [("stage", "STAGE"), ("pet", "PET")] {
        let f = &data["framing"][key];
        let t = f["target"].as_array().unwrap();
        writeln!(
            out,
            "pub const FRAMING_{name}: Framing = Framing {{ target: [{:?}, {:?}, {:?}], theta: {:?}, phi: {:?}, half_h: {:?}, half_w: {:?} }};",
            t[0].as_f64().unwrap(),
            t[1].as_f64().unwrap(),
            t[2].as_f64().unwrap(),
            f["theta"].as_f64().unwrap(),
            f["phi"].as_f64().unwrap(),
            f["halfH"].as_f64().unwrap(),
            f["halfW"].as_f64().unwrap()
        )
        .unwrap();
    }
    let screens = data["screens"].as_array().unwrap();
    let texts: Vec<String> = screens.iter().map(|s| format!("{:?}", s.as_str().unwrap())).collect();
    writeln!(out, "pub static SCREENS: [&str; {}] = [{}];", screens.len(), texts.join(", ")).unwrap();
    for (key, name) in [("open", "LAPTOP_OPEN"), ("typingFrom", "TYPING_FROM"), ("typingTo", "TYPING_TO")] {
        writeln!(out, "pub const {name}: usize = {};", data["laptop"][key].as_u64().unwrap()).unwrap();
    }
    let path = std::path::Path::new(&std::env::var("OUT_DIR").unwrap()).join("moves.rs");
    std::fs::write(path, out).unwrap();
}
